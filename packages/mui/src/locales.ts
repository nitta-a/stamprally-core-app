import type { LocaleDictionary } from "@stamprally/core";

export type BuiltInMuiLocale = "ja" | "en" | "zh-CN" | "zh-TW" | "ko";

export function resolveMuiLabel<TLocale extends string>(
  dictionary: LocaleDictionary<TLocale> | undefined,
  locale: TLocale,
  key: string,
  fallback: string,
): string {
  return (
    dictionary?.[locale]?.[key] ??
    DEFAULT_MUI_DICTIONARY[locale as BuiltInMuiLocale]?.[key] ??
    fallback
  );
}

